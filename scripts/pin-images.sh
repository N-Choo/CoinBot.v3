#!/usr/bin/env bash
# Resolve prod image digests and write docker-compose.prod.yml.
#
# Usage:
#   make pin-images                 # pin ghcr.io/<owner>/*:latest
#   make pin-images TAG=<sha>       # pin a specific CI build
#   GHCR_OWNER=someone make pin-images
#
# CI only rebuilds changed images, so a service whose :<sha> tag does not exist
# keeps its previous digest from docker-compose.prod.yml.
set -euo pipefail

OWNER="${GHCR_OWNER:-n-choo}"
TAG="${TAG:-latest}"

case "$OWNER" in
*[!A-Za-z0-9._-]*)
	echo "error: invalid GHCR_OWNER: $OWNER" >&2
	exit 1
	;;
esac
case "$TAG" in
*[!A-Za-z0-9._-]*)
	echo "error: invalid TAG: $TAG" >&2
	exit 1
	;;
esac

command -v docker >/dev/null 2>&1 || {
	echo "error: docker is required" >&2
	exit 1
}
docker buildx version >/dev/null 2>&1 || {
	echo "error: docker buildx is required" >&2
	exit 1
}

ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
OUT="$ROOT/docker-compose.prod.yml"

# compose service:image name
SERVICES=(
	"deposit-worker-prod:coinbot-worker"
	"withdraw-worker-prod:coinbot-withdraw-worker"
	"api_gateway-prod:coinbot-api_gateway"
	"frontend-prod:coinbot-frontend"
	"trade-engine-prod:coinbot-trade_engine"
	"signal-gateway-prod:coinbot-signal-gateway"
	"opencode:coinbot-opencode"
)

# Print the image currently pinned for a compose service, if any.
existing_image() {
	local service="$1"
	[ -f "$OUT" ] || return 1
	awk -v svc="$service" '
		$0 == "  " svc ":" { in_svc = 1; next }
		in_svc && /^  [A-Za-z0-9_-]+:/ { in_svc = 0 }
		in_svc && $1 == "image:" { print $2; exit }
	' "$OUT"
}

tmp="$(mktemp "$ROOT/.docker-compose.prod.yml.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
chmod 644 "$tmp"

{
	echo "# Generated by \`make pin-images\` from ghcr.io/${OWNER}/*:${TAG}."
	echo "# Do not edit by hand; run \`make pin-images\` to promote a new build."
	echo "services:"
} >"$tmp"

for entry in "${SERVICES[@]}"; do
	service="${entry%%:*}"
	image="${entry#*:}"
	ref="ghcr.io/${OWNER}/${image}:${TAG}"

	if digest="$(docker buildx imagetools inspect "$ref" \
		--format '{{.Manifest.Digest}}' 2>/dev/null)"; then
		case "$digest" in
		sha256:*) ;;
		*)
			echo "error: unexpected digest for $ref: $digest" >&2
			exit 1
			;;
		esac
		pinned="ghcr.io/${OWNER}/${image}@${digest}"
		echo "  ${ref} -> ${digest}" >&2
	elif existing="$(existing_image "$service")" &&
		[[ "$existing" == *"@sha256:"* ]]; then
		pinned="$existing"
		echo "  ${ref} not found; keeping existing pin ${existing##*@}" >&2
	else
		echo "error: cannot resolve $ref and no existing pin for ${service} (has CI pushed this image?)" >&2
		exit 1
	fi

	{
		echo "  ${service}:"
		echo "    image: ${pinned}"
	} >>"$tmp"
done

if cmp -s "$tmp" "$OUT"; then
	echo "No image changes."
else
	mv "$tmp" "$OUT"
	echo "Wrote $OUT"
fi
